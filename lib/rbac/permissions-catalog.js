/**
 * ============================================================================
 * AapliSociety RBAC — Canonical Permission Catalog
 * ============================================================================
 * SINGLE SOURCE OF TRUTH for every permission in the system.
 *
 * Permission id format:  <module>.<resource>.<action>   (camelCase segments)
 *   - Page-access permission for a page  ->  <module>.<pageKey>.view
 *   - Business/action permission         ->  <module>.<resource>.<action>
 *   - Wildcards (authoring only)          ->  <module>.<resource>.*  |  <module>.*
 *     (there is NO global "*" — deny-by-default forbids it)
 *
 * Every page in the app MUST appear here with `page: true` so the CI guard
 * (scripts/check-permission-registry.js) can prove no page ships without a
 * page-access permission. Every destructive/irreversible action MUST set
 * `dangerous: true` so the admin picker can surface a ⚠ indicator.
 *
 * Plugins/future modules do NOT edit this file. They call
 * registry.registerModule(moduleDef) at boot (see lib/rbac/registry.js).
 * ============================================================================
 */

